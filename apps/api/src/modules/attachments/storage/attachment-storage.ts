import { randomUUID } from 'node:crypto';

/** Injection token for the storage implementation. */
export const ATTACHMENT_STORAGE = Symbol('ATTACHMENT_STORAGE');

/** Thrown by `read` when there is no file for the key. */
export class StorageFileNotFoundError extends Error {
  constructor() {
    super('Stored file not found');
    this.name = 'StorageFileNotFoundError';
  }
}

/** Thrown when the storage cannot write, read or remove. Never carries file system paths. */
export class StorageFailureError extends Error {
  constructor(operation: 'write' | 'read' | 'remove' | 'list', code?: string) {
    super(`Storage ${operation} failed${code ? ` (${code})` : ''}`);
    this.name = 'StorageFailureError';
  }
}

/** A file found in the storage, for the orphan cleanup. */
export interface StoredFileInfo {
  storageKey: string;
  modifiedAt: Date;
}

/**
 * Where attachment bytes live. The database keeps only metadata and the `storageKey`.
 * Keys are always generated by the server with `generateStorageKey()`.
 */
export interface AttachmentStorage {
  /** Fails if the key already exists (keys are unique). */
  save(storageKey: string, content: Buffer): Promise<void>;
  /** Throws `StorageFileNotFoundError` if missing. */
  read(storageKey: string): Promise<Buffer>;
  /** Idempotent: removing a missing file is not an error. */
  remove(storageKey: string): Promise<void>;
  /** Every stored file with a valid key (anything else in the folder is ignored). */
  list(): Promise<StoredFileInfo[]>;
}

export const STORAGE_KEY_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function generateStorageKey(): string {
  return randomUUID();
}

export function isValidStorageKey(storageKey: string): boolean {
  return STORAGE_KEY_PATTERN.test(storageKey);
}
